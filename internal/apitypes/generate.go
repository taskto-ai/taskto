package apitypes

import (
	"bytes"
	"encoding"
	"encoding/json"
	"errors"
	"fmt"
	"reflect"
	"regexp"
	"slices"
	"strings"
	"time"
	"unicode"

	"taskto.ai/taskto/internal/apierr"
)

const Header = `// Code generated by go generate ./internal/apitypes; DO NOT EDIT.
//
// The shapes of the server's JSON replies, read from the Go structs that are written as them
// (internal/apitypes lists which). api.contract.ts checks the types api.ts declares against
// these, so a field renamed or retyped in Go fails the web build. See docs/api.md#api-types.
`

type generator struct {
	registered map[reflect.Type]string
	names      map[reflect.Type]string
	bodies     map[string]string
	todo       []reflect.Type
	nonNull    []string
	where      string
	expanding  map[reflect.Type]bool
	errs       []error
}

var (
	timeType      = reflect.TypeFor[time.Time]()
	rawType       = reflect.TypeFor[json.RawMessage]()
	numberType    = reflect.TypeFor[json.Number]()
	jsonMarshaler = reflect.TypeFor[json.Marshaler]()
	textMarshaler = reflect.TypeFor[encoding.TextMarshaler]()
	identifier    = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)
)

var wireShapes = map[reflect.Type]wire{
	timeType:                         {ts: "string"},
	reflect.TypeFor[apierr.Params](): {ts: "Record<string, string | number>", null: true},
}

type wire struct {
	ts   string
	null bool
}

const tagName = "apitypes"

func Generate(roots []Root) ([]byte, error) {
	out, _, err := generate(roots)
	return out, err
}

func NonNullFields(roots []Root) ([]string, error) {
	_, g, err := generate(roots)
	if err != nil {
		return nil, err
	}
	out := slices.Clone(g.nonNull)
	slices.Sort(out)
	return slices.Compact(out), nil
}

func generate(roots []Root) ([]byte, *generator, error) {
	g := &generator{
		registered: map[reflect.Type]string{},
		names:      map[reflect.Type]string{},
		bodies:     map[string]string{},
	}
	for _, r := range roots {
		t := derefAll(r.Type)
		if t.Kind() != reflect.Struct {
			return nil, nil, fmt.Errorf("apitypes: %s is %s, not a struct", r.Name, t)
		}
		if _, known := wireShapes[t]; known || hasMarshaler(t) {
			return nil, nil, fmt.Errorf("apitypes: %s (%s) writes itself with a MarshalJSON or MarshalText, so its struct says nothing of its JSON: register its wire shape", r.Name, t)
		}
		if prev, dup := g.registered[t]; dup {
			return nil, nil, fmt.Errorf("apitypes: %s is listed twice (%s, %s)", t, prev, r.Name)
		}
		g.registered[t] = r.Name
	}
	for _, r := range roots {
		g.name(derefAll(r.Type))
	}
	for len(g.todo) > 0 {
		t := g.todo[0]
		g.todo = g.todo[1:]
		body := g.structBody(t)
		g.bodies[g.names[t]] = body
	}
	if len(g.errs) > 0 {
		return nil, nil, errors.Join(g.errs...)
	}
	keys := make([]string, 0, len(g.bodies))
	for k := range g.bodies {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	var out bytes.Buffer
	out.WriteString(Header)
	for _, k := range keys {
		fmt.Fprintf(&out, "\nexport type %s = %s\n", k, g.bodies[k])
	}
	return out.Bytes(), g, nil
}

func (g *generator) name(t reflect.Type) string {
	if n, ok := g.names[t]; ok {
		return n
	}
	n, ok := g.registered[t]
	if !ok {
		n = pascal(pkgName(t)) + pascal(t.Name())
	}
	for other, name := range g.names {
		if name == n && other != t {
			g.fail("%s and %s are both called %s: list one of them under another name", other, t, n)
		}
	}
	if !identifier.MatchString(n) {
		g.fail("%s would be called %q, which is not a TypeScript name: list the type under another name", t, n)
	}
	g.names[t] = n
	g.todo = append(g.todo, t)
	return n
}

func (g *generator) fail(format string, args ...any) {
	msg := fmt.Sprintf(format, args...)
	if g.where != "" {
		msg += " (at " + g.where + ")"
	}
	g.errs = append(g.errs, errors.New("apitypes: "+msg))
}

type field struct {
	name     string
	optional bool
	nonNull  bool
	nilOmit  bool
	free     bool
	typ      reflect.Type
	depth    int
	tagged   bool
	owner    reflect.Type
	goName   string
	promised bool
}

func (g *generator) structBody(t reflect.Type) string {
	byName := map[string][]field{}
	var order []string
	for _, f := range collect(t, 0, false, map[reflect.Type]bool{}) {
		if _, seen := byName[f.name]; !seen {
			order = append(order, f.name)
		}
		byName[f.name] = append(byName[f.name], f)
	}
	best := map[string]field{}
	for name, fs := range byName {
		top := slices.MinFunc(fs, func(a, b field) int { return a.depth - b.depth }).depth
		var shallow, tagged []field
		for _, f := range fs {
			if f.depth == top {
				shallow = append(shallow, f)
				if f.tagged {
					tagged = append(tagged, f)
				}
			}
		}
		if len(tagged) > 0 {
			shallow = tagged
		}
		if len(shallow) != 1 {
			g.fail("%s: the field %q is ambiguous (encoding/json writes none of them)", t, name)
			return "unknown"
		}
		best[name] = shallow[0]
	}
	var b strings.Builder
	b.WriteString("{\n")
	for _, name := range order {
		f := best[name]
		key := name
		if !identifier.MatchString(key) {
			key = fmt.Sprintf("%q", key)
		}
		opt := ""
		if f.optional {
			opt = "?"
		}
		outer := g.where
		g.where = f.owner.String() + "." + f.goName
		typ, nullable := g.tsType(f.typ, f.free)
		g.where = outer
		if f.promised {
			if !nullable {
				g.fail("%s.%s: apitypes:\"nonnull\" on a field that is never null", f.owner, f.goName)
			}
			g.nonNull = append(g.nonNull, f.owner.PkgPath()+"."+f.owner.Name()+"."+f.goName)
		}
		if f.nilOmit {
			nullable = nullable && f.typ.Kind() == reflect.Pointer && nilable(f.typ.Elem())
		}
		if nullable && !f.nonNull {
			typ += " | null"
		}
		fmt.Fprintf(&b, "  %s%s: %s\n", key, opt, typ)
	}
	b.WriteString("}")
	return b.String()
}

func collect(t reflect.Type, depth int, viaPointer bool, seen map[reflect.Type]bool) []field {
	if seen[t] {
		return nil
	}
	seen[t] = true
	defer delete(seen, t)
	var out []field
	for sf := range t.Fields() {
		if sf.Anonymous {
			et := sf.Type
			if et.Kind() == reflect.Pointer {
				et = et.Elem()
			}
			if !sf.IsExported() && et.Kind() != reflect.Struct {
				continue
			}
		} else if !sf.IsExported() {
			continue
		}
		tag := sf.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if !validTag(name) {
			name = ""
		}
		ft := sf.Type
		if ft.Name() == "" && ft.Kind() == reflect.Pointer {
			ft = ft.Elem()
		}
		if name == "" && sf.Anonymous && ft.Kind() == reflect.Struct {
			out = append(out, collect(ft, depth+1, viaPointer || sf.Type.Kind() == reflect.Pointer, seen)...)
			continue
		}
		tagged := name != ""
		if name == "" {
			name = sf.Name
		}
		omitEmpty := hasOpt(opts, "omitempty") && emptyable(sf.Type)
		omitZero := hasOpt(opts, "omitzero")
		nilOmitted := (omitEmpty && nilable(sf.Type)) || (omitZero && !hasIsZero(sf.Type))
		typ := sf.Type
		if hasOpt(opts, "string") {
			typ = quoted(typ)
		}
		tags := sf.Tag.Get(tagName)
		out = append(out, field{
			name:     name,
			optional: viaPointer || omitEmpty || omitZero,
			nonNull:  hasOpt(tags, "nonnull"),
			nilOmit:  nilOmitted,
			free:     hasOpt(tags, "json"),
			promised: hasOpt(tags, "nonnull"),
			typ:      typ,
			depth:    depth,
			tagged:   tagged,
			owner:    t,
			goName:   sf.Name,
		})
	}
	return out
}

func validTag(s string) bool {
	if s == "" {
		return false
	}
	for _, c := range s {
		switch {
		case strings.ContainsRune("!#$%&()*+-./:;<=>?@[]^_{|}~ ", c):
		case !unicode.IsLetter(c) && !unicode.IsDigit(c):
			return false
		}
	}
	return true
}

func emptyable(t reflect.Type) bool {
	switch t.Kind() {
	case reflect.Array:
		return t.Len() == 0
	case reflect.Map, reflect.Slice, reflect.String, reflect.Bool,
		reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr,
		reflect.Float32, reflect.Float64, reflect.Interface, reflect.Pointer:
		return true
	}
	return false
}

func nilable(t reflect.Type) bool {
	switch t.Kind() {
	case reflect.Map, reflect.Slice, reflect.Interface, reflect.Pointer:
		return true
	}
	return false
}

func hasIsZero(t reflect.Type) bool {
	type zeroer interface{ IsZero() bool }
	z := reflect.TypeFor[zeroer]()
	return t.Implements(z) || reflect.PointerTo(t).Implements(z)
}

func quoted(t reflect.Type) reflect.Type {
	if t.Kind() == reflect.Pointer {
		if q := quotedScalar(t.Elem()); q != t.Elem() {
			return reflect.PointerTo(q)
		}
		return t
	}
	return quotedScalar(t)
}

func quotedScalar(t reflect.Type) reflect.Type {
	if hasMarshaler(t) {
		return t
	}
	switch t.Kind() {
	case reflect.Bool, reflect.String, reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr,
		reflect.Float32, reflect.Float64:
		return reflect.TypeFor[string]()
	}
	return t
}

func hasOpt(opts, want string) bool {
	for o := range strings.SplitSeq(opts, ",") {
		if o == want {
			return true
		}
	}
	return false
}

func hasMarshaler(t reflect.Type) bool {
	pt := reflect.PointerTo(t)
	return t.Implements(jsonMarshaler) || pt.Implements(jsonMarshaler) ||
		t.Implements(textMarshaler) || pt.Implements(textMarshaler)
}

func derefAll(t reflect.Type) reflect.Type {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	return t
}

func (g *generator) tsType(t reflect.Type, free bool) (string, bool) {
	return g.tsTypeVia(t, free, false)
}

func (g *generator) tsTypeVia(t reflect.Type, free, viaPtr bool) (string, bool) {
	if t.Kind() == reflect.Pointer {
		inner, _ := g.tsTypeVia(t.Elem(), free, true)
		return inner, true
	}
	if w, ok := wireShapes[t]; ok {
		return w.ts, w.null
	}
	if t == rawType {
		if !free {
			g.fail("a json.RawMessage is any JSON: tag its field apitypes:\"json\"")
		}
		return "unknown", false
	}
	if t == numberType {
		return "number", false
	}
	if !viaPtr && hasMarshaler(t) && !t.Implements(jsonMarshaler) && !t.Implements(textMarshaler) {
		g.fail("%s has a marshaler on its pointer only, which encoding/json uses when it can address the value: make it a value method or reach it through a pointer", t)
		return "unknown", false
	}
	switch {
	case isText(t):
		return "string", false
	case hasMarshaler(t):
		g.fail("%s writes itself with a MarshalJSON, so its struct says nothing of its JSON: register its wire shape", t)
		return "unknown", false
	}
	switch t.Kind() {
	case reflect.Bool:
		return "boolean", false
	case reflect.String:
		return "string", false
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr,
		reflect.Float32, reflect.Float64:
		return "number", false
	case reflect.Interface:
		if !free {
			g.fail("%s is any JSON: tag its field apitypes:\"json\", or give it a type", t)
		}
		return "unknown", false
	case reflect.Slice, reflect.Array, reflect.Map:
		if g.expanding[t] {
			g.fail("%s holds itself, which has no TypeScript type written in place: make it a struct", t)
			return "unknown", false
		}
		if g.expanding == nil {
			g.expanding = map[reflect.Type]bool{}
		}
		g.expanding[t] = true
		defer delete(g.expanding, t)
	}
	switch t.Kind() {
	case reflect.Slice, reflect.Array:
		if t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 && !hasMarshaler(t.Elem()) {
			return "string", true
		}
		return wrap(g.element(t.Elem(), free)) + "[]", t.Kind() == reflect.Slice
	case reflect.Map:
		if !mapKeyOK(t.Key()) {
			g.fail("%s: a map's key must be text or a number", t)
		}
		return "Record<string, " + g.element(t.Elem(), free) + ">", true
	case reflect.Struct:
		if t.Name() == "" {
			return strings.ReplaceAll(g.structBody(t), "\n", "\n  "), false
		}
		return g.name(t), false
	}
	g.fail("%s can't be told as JSON", t)
	return "unknown", false
}

func (g *generator) element(t reflect.Type, free bool) string {
	s, nullable := g.tsType(t, free)
	if nullable {
		return s + " | null"
	}
	return s
}

func mapKeyOK(k reflect.Type) bool {
	switch k.Kind() {
	case reflect.String,
		reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr:
		return true
	}
	return k.Implements(textMarshaler)
}

func isText(t reflect.Type) bool {
	pt := reflect.PointerTo(t)
	return (t.Implements(textMarshaler) || pt.Implements(textMarshaler)) &&
		!t.Implements(jsonMarshaler) && !pt.Implements(jsonMarshaler)
}

func wrap(s string) string {
	if strings.Contains(s, " | ") {
		return "(" + s + ")"
	}
	return s
}

func pkgName(t reflect.Type) string {
	p := t.PkgPath()
	if i := strings.LastIndex(p, "/"); i >= 0 {
		p = p[i+1:]
	}
	return p
}

func pascal(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}
